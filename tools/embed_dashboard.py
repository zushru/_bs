#!/usr/bin/env python3
"""Generate the ESP32 PROGMEM header from the canonical dashboard HTML."""
from __future__ import annotations

import hashlib
import os
import tempfile
from pathlib import Path

_RUN_AS_PLATFORMIO = False
try:
    Import("env")  # type: ignore[name-defined]
    ROOT = Path(env.subst("$PROJECT_DIR")).resolve()  # type: ignore[name-defined]
    _RUN_AS_PLATFORMIO = True
except NameError:
    ROOT = Path(__file__).resolve().parents[1]

SOURCE = ROOT / "web/dashboard/index.html"
OUTPUT = ROOT / "target/esp32_attendance/dashboard_html.h"
DELIMITER = "ATT_DASHBOARD"


def render_header(html: str) -> str:
    if f'){DELIMITER}"' in html:
        raise ValueError("dashboard contains the reserved C++ raw-string terminator")
    digest = hashlib.sha256(html.encode("utf-8")).hexdigest()
    return (
        "#pragma once\n"
        "// Generated from web/dashboard/index.html; do not edit this file directly.\n"
        f"// SHA-256: {digest}\n"
        f"static const char kDashboardHtml[] PROGMEM = R\"{DELIMITER}("
        + html
        + f"){DELIMITER}\";\n"
    )


def atomic_write(path: Path, content: str) -> None:
    encoded = content.encode("utf-8")
    if path.exists() and path.read_bytes() == encoded:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix="." + path.name + ".", dir=str(path.parent))
    try:
        with os.fdopen(fd, "wb") as stream:
            stream.write(encoded)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def main() -> None:
    html = SOURCE.read_text(encoding="utf-8")
    if not html.startswith("<!doctype html>") or "</html>" not in html:
        raise SystemExit("dashboard source is not a complete HTML document")
    atomic_write(OUTPUT, render_header(html))
    print("ATT dashboard embedded: " + hashlib.sha256(html.encode("utf-8")).hexdigest())


if _RUN_AS_PLATFORMIO or __name__ == "__main__":
    main()
